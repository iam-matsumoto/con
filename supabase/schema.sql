create policy "authenticated users can manage schedules" on public.schedules for all to authenticated using (true) with check (true);
create policy "authenticated users can read schedule employees" on public.schedule_employees for select to authenticated using (true);
create policy "authenticated users can manage schedule employees" on public.schedule_employees for all to authenticated using (true) with check (true);
create policy "authenticated users can read attendance" on public.attendance for select to authenticated using (true);
create policy "authenticated users can manage attendance" on public.attendance for all to authenticated using (true) with check (true);
create policy "authenticated users can read notices" on public.notices for select to authenticated using (true);
